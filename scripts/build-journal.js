/* ═══════════════════════════════════════════════════
   EURO POLO · build-journal.js

   Generates, from content/ :
     • one HTML page per article        content/journal/<slug>.md → <slug>.html
     • the Journal hub                  blog.html
     • the whole sitemap                sitemap.xml

   Publishing a new article is one file: drop a .md into content/journal/
   (copy _TEMPLATE.md), then run this. The hub, the category grouping, the
   related-articles blocks, the JSON-LD and the sitemap all follow.

     node scripts/build-journal.js            write
     node scripts/build-journal.js --check    exit 1 if the committed output
                                              is out of date (no writes)

   The site has no build step — Vercel serves the repo as-is — so this runs
   on a workstation and its output is committed. scripts/ and content/ are
   both listed in .vercelignore and are never served.

   Re-run it after regenerating product data: the "Shop this guide" cards
   bake in name / price / image from data/product-data.json.
═══════════════════════════════════════════════════ */

