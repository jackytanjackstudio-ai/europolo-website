class BuildError extends Error {}

/* ═══════════ small helpers ═══════════ */

const readText = f => fs.readFileSync(f, 'utf8').replace(/^﻿/, '');
const rel = f => path.relative(ROOT, f).split(path.sep).join('/');

/* Fill {{placeholders}}. Every placeholder must have a value, and every value
   must be used — a typo in either direction fails the build. */
function fill(template, vars, label) {
  const seen = new Set();
  const out = template.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (_m, key) => {
    if (!(key in vars)) throw new BuildError(`${label}: template asks for {{${key}}}, which the generator does not provide`);
    seen.add(key);
    return vars[key];
  });
  for (const key of Object.keys(vars)) {
    if (!seen.has(key)) throw new BuildError(`${label}: generated {{${key}}} but the template never uses it`);
  }
  /* An optional block that rendered empty leaves its own blank line behind. */
  return out.replace(/\n{3,}/g, '\n\n');
}

/* Indent a multi-line block so it sits correctly inside the template. */
function indent(html, spaces) {
  const pad = ' '.repeat(spaces);
  return String(html)
    .split('\n')
    .map(line => (line.trim() === '' ? '' : pad + line))
    .join('\n');
}

function parseDate(value, where) {
  const s = String(value == null ? '' : value).trim();
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(s);
  if (!m) throw new BuildError(`${where}: expected a date as YYYY-MM-DD, found ${JSON.stringify(s)}`);
  const [, y, mo, d] = m;
  const month = parseInt(mo, 10), day = parseInt(d, 10);
  if (month < 1 || month > 12 || day < 1 || day > 31) throw new BuildError(`${where}: ${s} is not a real date`);
  return {
    iso: s,
    sort: Number(y + mo + d),
    long: `${day} ${MONTHS[month - 1]} ${y}`,
    short: `${day} ${MONTHS[month - 1].slice(0, 3)} ${y}`
  };
}

/* ── lastmod source: the file's last commit date, or its mtime when the
      working tree has uncommitted changes (or git is unavailable). ── */
let dirtyPaths = null;
function loadDirtyPaths() {
  if (dirtyPaths) return dirtyPaths;
  dirtyPaths = new Set();
  try {
    const out = cp.execFileSync('git', ['status', '--porcelain'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
    out.split('\n').forEach(line => {
      const p = line.slice(3).trim().replace(/^"|"$/g, '');
      if (p) dirtyPaths.add(p.split(' -> ').pop());
    });
  } catch { /* not a git checkout — fall back to mtimes */ }
  return dirtyPaths;
}

const fileDateCache = new Map();
function fileDate(relPath) {
  if (fileDateCache.has(relPath)) return fileDateCache.get(relPath);
  const abs = path.join(ROOT, relPath);
  let result = null;
  if (!loadDirtyPaths().has(relPath)) {
    try {
      const out = cp.execFileSync('git', ['log', '-1', '--format=%cs', '--', relPath],
        { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
      if (/^\d{4}-\d{2}-\d{2}$/.test(out)) result = out;
    } catch { /* fall through to mtime */ }
  }
  if (!result) {
    try { result = new Date(fs.statSync(abs).mtime).toISOString().slice(0, 10); }
    catch { result = new Date().toISOString().slice(0, 10); }
  }
  fileDateCache.set(relPath, result);
  return result;
}

/* ═══════════ config ═══════════ */

function loadConfig() {
  const file = path.join(CONTENT_DIR, 'site.yml');
  const cfg = parseYaml(readText(file), rel(file), 1);
  for (const key of ['site', 'hub', 'categories', 'article', 'sitemap']) {
    if (!cfg[key]) throw new BuildError(`${rel(file)}: missing "${key}" section`);
  }
  cfg.categoryBySlug = new Map();
  cfg.categories.forEach(cat => {
    if (!cat.slug || !cat.label || !cat.section) {
      throw new BuildError(`${rel(file)}: every category needs slug, label and section`);
    }
    cfg.categoryBySlug.set(cat.slug, cat);
  });
  cfg.origin = String(cfg.site.origin).replace(/\/+$/, '');
  return cfg;
}

const absUrl = (cfg, p) => `${cfg.origin}/${String(p).replace(/^\/+/, '')}`;

/* ═══════════ product catalogue ═══════════ */

const normSku = s => String(s == null ? '' : s).replace(/\s+/g, '').toUpperCase();

function loadCatalogue(cfg) {
  const relSource = cfg.sitemap.products.source;
  const file = path.join(ROOT, relSource);
  const data = JSON.parse(readText(file));
  const products = data.products || [];
  const bySku = new Map();
  const byId = new Map();
  products.forEach(p => {
    byId.set(String(p.id).toUpperCase(), p);
    (p.variants || []).forEach(v => {
      const key = normSku(v.sku);
      if (key && !bySku.has(key)) bySku.set(key, p);
    });
  });
  return { products, bySku, byId, source: relSource };
}

/* ═══════════ articles ═══════════ */

function requireField(data, key, where) {
  const value = data[key];
  if (value === undefined || value === null || String(value).trim() === '') {
    throw new BuildError(`${where}: "${key}" is required in the front matter`);
  }
  return value;
}

function loadArticle(file, cfg) {
  const where = rel(file);
  const { data, body } = parseFrontMatter(readText(file), where);

  const slug = String(data.slug || path.basename(file, '.md')).trim();
  if (!/^[a-z0-9][a-z0-9-]*$/.test(slug)) {
    throw new BuildError(`${where}: slug ${JSON.stringify(slug)} must be lower-case letters, numbers and hyphens`);
  }

  const title = String(requireField(data, 'title', where)).trim();
  const description = String(requireField(data, 'description', where)).trim();
  const categorySlug = String(requireField(data, 'category', where)).trim();
  const category = cfg.categoryBySlug.get(categorySlug);
  if (!category) {
    throw new BuildError(`${where}: unknown category "${categorySlug}" — add it to content/site.yml or use one of: ` +
      [...cfg.categoryBySlug.keys()].join(', '));
  }

  const published = parseDate(requireField(data, 'published', where), `${where} (published)`);
  const updated = data.updated ? parseDate(data.updated, `${where} (updated)`) : published;
  if (updated.sort < published.sort) throw new BuildError(`${where}: "updated" is earlier than "published"`);

  const hero = data.hero || {};
  if (!hero.src) throw new BuildError(`${where}: "hero.src" is required`);
  if (!hero.alt) throw new BuildError(`${where}: "hero.alt" is required — it is the image's accessible name and an SEO signal`);
  const heroFile = path.join(ROOT, String(hero.src));
  const probe = H.imageSize(heroFile);
  if (!probe) {
    throw new BuildError(`${where}: cannot read hero image ${hero.src} — check the path (relative to the site root)`);
  }
  const heroWidth = hero.width || probe.width;
  const heroHeight = hero.height || probe.height;
  if (!heroWidth || !heroHeight) {
    throw new BuildError(`${where}: could not determine the size of ${hero.src} — set hero.width and hero.height`);
  }
  const heroKB = Math.round(probe.bytes / 1024);
  if (heroKB > (cfg.article.heroMaxKB || 300)) {
    warn(`${where}: hero image is ${heroKB} KB (target ${cfg.article.heroMaxKB} KB) — re-export it smaller; it is the LCP element`);
  }

  const words = markdown.wordCount(body);
  const minutes = Math.max(1, Math.round(words / (cfg.article.wordsPerMinute || 200)));
  const readTime = data.readTime ? String(data.readTime) : `${minutes} min read`;

  const subtitle = data.subtitle ? String(data.subtitle).trim() : '';
  const shortTitle = data.shortTitle
    ? String(data.shortTitle).trim()
    : (title.includes(': ') ? title.split(': ')[0] : title);

  const faq = (data.faq || []).map((item, i) => {
    if (!item || !item.q || !item.a) throw new BuildError(`${where}: faq item ${i + 1} needs both "q" and "a"`);
    return { q: String(item.q).trim(), a: String(item.a).trim() };
  });

  return {
    file, where, slug,
    path: `${slug}.html`,
    draft: data.draft === true,
    title, shortTitle, subtitle, description,
    pageTitle: data.pageTitle ? String(data.pageTitle) : `${title} | ${cfg.site.titleSuffix}`,
    ogTitle: data.ogTitle ? String(data.ogTitle) : title,
    ogDescription: String(data.ogDescription || subtitle || description),
    excerpt: String(data.excerpt || subtitle || description),
    keywords: data.keywords ? String(data.keywords) : '',
    category, topic: data.topic ? String(data.topic) : '',
    published, updated, readTime, words,
    hero: {
      src: String(hero.src),
      alt: String(hero.alt).trim(),
      caption: hero.caption ? String(hero.caption) : '',
      width: heroWidth,
      height: heroHeight,
      titleInHero: hero.titleInHero === true
    },
    shop: data.shop || null,
    faq,
    faqHeading: data.faqHeading ? String(data.faqHeading) : 'Frequently Asked Questions',
    cta: data.cta || null,
    body
  };
}

function loadArticles(cfg) {
  if (!fs.existsSync(ARTICLE_DIR)) throw new BuildError(`missing ${rel(ARTICLE_DIR)}`);
  const files = fs.readdirSync(ARTICLE_DIR)
    .filter(f => f.endsWith('.md') && !f.startsWith('_'))
    .sort()
    .map(f => path.join(ARTICLE_DIR, f));

  const all = files.map(f => loadArticle(f, cfg));
  const bySlug = new Map();
  all.forEach(a => {
    if (bySlug.has(a.slug)) throw new BuildError(`${a.where}: slug "${a.slug}" is already used by ${bySlug.get(a.slug).where}`);
    bySlug.set(a.slug, a);
  });

  const published = all.filter(a => !a.draft);
  all.filter(a => a.draft).forEach(a => warn(`${a.where}: draft — not published, not listed, not in the sitemap`));

  /* Newest first; a stable tiebreak keeps output deterministic. */
  published.sort((a, b) => (b.published.sort - a.published.sort) || a.slug.localeCompare(b.slug));
  return published;
}

