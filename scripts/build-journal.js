/* "Shop this guide" — product cards resolved from data/product-data.json.
   Name, price and cover image are baked in at build time; the card links to
   product.html, which owns variants, live stock and Add to Cart. */
function shopSection(article, catalogue) {
  const shop = article.shop;
  if (!shop) return '';
  const items = shop.items || [];
  if (!items.length) throw new BuildError(`${article.where}: "shop" has no items`);

  const cards = items.map((item, i) => {
    const at = `${article.where}: shop item ${i + 1}`;
    if (!item.sku && !item.id) throw new BuildError(`${at} needs a "sku" (or an "id")`);
    const product = item.id
      ? catalogue.byId.get(String(item.id).toUpperCase())
      : catalogue.bySku.get(normSku(item.sku));
    if (!product) {
      throw new BuildError(`${at}: ${item.sku || item.id} is not in ${catalogue.source} — check the SKU`);
    }
    if (!product.inStock) warn(`${at}: ${product.id} (${item.sku || item.id}) is out of stock right now`);

    const name = item.label ? String(item.label) : product.name;
    const cover = (product.images && product.images.cover) || '';
    if (!cover) throw new BuildError(`${at}: ${product.id} has no cover image`);
    const size = /^https?:/i.test(cover) ? null : H.imageSize(path.join(ROOT, cover));
    const dims = size && size.width ? ` width="${size.width}" height="${size.height}"` : '';
    const kicker = item.kicker
      ? `\n        <span class="shop-card__kicker">${H.text(item.kicker)}</span>`
      : '';

    return `    <a class="shop-card" href="product.html?id=${H.escapeHtml(product.id)}">
      <span class="shop-card__media">
        <img src="${H.escapeHtml(cover)}" alt="${H.text(product.name)}"${dims} loading="lazy" decoding="async" />
      </span>
      <span class="shop-card__body">${kicker}
        <span class="shop-card__name">${H.text(name)}</span>
        <span class="shop-card__price">${H.text(product.priceDisplay || '')}</span>
        <span class="shop-card__cta">View product &rarr;</span>
      </span>
    </a>`;
  });

  const eyebrow = shop.eyebrow ? `\n  <p class="shop-guide__eyebrow">${H.text(shop.eyebrow)}</p>` : '';
  const intro = shop.intro ? `\n  <p class="shop-guide__intro">${H.text(shop.intro)}</p>` : '';
  const heading = H.text(shop.heading || 'Shop this guide');

  return `<aside class="shop-guide" aria-label="${H.text(shop.heading || 'Shop this guide')}">${eyebrow}
  <h2 class="shop-guide__title">${heading}</h2>${intro}
  <div class="shop-guide__grid">
${cards.join('\n')}
  </div>
</aside>`;
}

function faqSection(article) {
  if (!article.faq.length) return '';
  const items = article.faq.map(item => {
    const answer = markdown.render(item.a, {}).html.map(block => indent(block, 6)).join('\n');
    return `  <div class="faq-item">
    <h3 class="faq-item__q" id="faq-${H.slugify(item.q)}">${markdown.inline(item.q)}</h3>
    <div class="faq-item__a">
${answer}
    </div>
  </div>`;
  });
  return `<section class="article-faq" aria-labelledby="article-faq-title">
  <h2 class="article-faq__title" id="article-faq-title">${H.text(article.faqHeading)}</h2>
${items.join('\n')}
</section>`;
}

function ctaBlock(article) {
  const cta = article.cta;
  if (!cta) return '';
  for (const key of ['heading', 'href', 'label']) {
    if (!cta[key]) throw new BuildError(`${article.where}: "cta.${key}" is required when a cta block is present`);
  }
  const body = cta.body ? `\n        <p>${H.text(cta.body)}</p>` : '';
  return `
      <!-- ── Closing CTA ── -->
      <div class="article-cta">
        <h3>${H.text(cta.heading)}</h3>${body}
        <a href="${H.escapeHtml(cta.href)}" class="btn btn--gold">${H.text(cta.label)}</a>
      </div>
`;
}

/* The listing card, shared by the hub and by the related-articles block. */
function journalCard(article, headingLevel) {
  const href = H.escapeHtml(article.path);
  return `<article class="journal-card">
  <a href="${href}" class="journal-card__media" aria-label="Read: ${H.text(article.shortTitle)}">
    <img src="${H.escapeHtml(article.hero.src)}"
         alt="${H.text(article.hero.alt)}"
         width="${article.hero.width}" height="${article.hero.height}" loading="lazy" decoding="async" />
  </a>
  <div class="journal-card__body">
    <div class="journal-card__meta">
      <span class="journal-card__tag">${H.text(article.category.label)}</span>
      <span class="sep">&middot;</span>
      <time datetime="${article.published.iso}">${H.text(article.published.short)}</time>
      <span class="sep">&middot;</span>
      <span>${H.text(article.readTime)}</span>
    </div>
    <h${headingLevel} class="journal-card__title">
      <a href="${href}">${H.text(article.title)}</a>
    </h${headingLevel}>
    <p class="journal-card__excerpt">${H.text(article.excerpt)}</p>
    <a href="${href}" class="journal-card__more">Read more &rarr;</a>
  </div>
</article>`;
}

function relatedBlock(article, articles, cfg) {
  const limit = cfg.article.relatedCount || 3;
  const others = articles.filter(a => a.slug !== article.slug);
  const sameCategory = others.filter(a => a.category.slug === article.category.slug);
  const picked = sameCategory.slice(0, limit);
  if (picked.length < limit) {
    others.filter(a => a.category.slug !== article.category.slug)
      .slice(0, limit - picked.length)
      .forEach(a => picked.push(a));
  }
  if (!picked.length) return '';

  const allSameCategory = picked.every(a => a.category.slug === article.category.slug);
  const heading = allSameCategory ? `More in ${article.category.section}` : 'More from the Journal';
  const cards = picked.map(a => indent(journalCard(a, 3), 10)).join('\n');

  return `
    <!-- ═══════════════════ RELATED ARTICLES ═══════════════════ -->
    <section class="article-related" aria-labelledby="article-related-title">
      <div class="article-related__inner">
        <div class="article-related__head">
          <h2 class="article-related__title" id="article-related-title">${H.text(heading)}</h2>
          <a href="blog.html" class="article-related__all">All articles &rarr;</a>
        </div>
        <div class="journal-grid">
${cards}
        </div>
      </div>
    </section>
`;
}

/* ═══════════ JSON-LD ═══════════ */

function jsonLdScript(graph) {
  return indent(JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2), 2);
}

function articleGraph(article, cfg) {
  const url = absUrl(cfg, article.path);
  const graph = [
    {
      '@type': 'BlogPosting',
      '@id': `${url}#article`,
      headline: H.plain(H.smartQuotes(article.title)),
      description: H.plain(H.smartQuotes(article.description)),
      image: {
        '@type': 'ImageObject',
        url: absUrl(cfg, article.hero.src),
        width: article.hero.width,
        height: article.hero.height
      },
      datePublished: article.published.iso,
      dateModified: article.updated.iso,
      author: { '@type': 'Organization', name: cfg.site.brand, url: `${cfg.origin}/` },
      publisher: {
        '@type': 'Organization',
        name: cfg.site.brand,
        logo: { '@type': 'ImageObject', url: absUrl(cfg, cfg.site.logo) }
      },
      mainEntityOfPage: { '@type': 'WebPage', '@id': url },
      articleSection: article.category.section,
      inLanguage: 'en-MY',
      wordCount: article.words,
      isPartOf: { '@type': 'Blog', '@id': `${absUrl(cfg, cfg.hub.path)}#blog` },
      breadcrumb: { '@id': `${url}#breadcrumb` }
    },
    {
      '@type': 'BreadcrumbList',
      '@id': `${url}#breadcrumb`,
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: `${cfg.origin}/` },
        { '@type': 'ListItem', position: 2, name: 'Journal', item: absUrl(cfg, cfg.hub.path) },
        { '@type': 'ListItem', position: 3, name: H.plain(H.smartQuotes(article.shortTitle)), item: url }
      ]
    }
  ];
  if (article.keywords) graph[0].keywords = H.plain(H.smartQuotes(article.keywords));

  if (article.faq.length) {
    graph.push({
      '@type': 'FAQPage',
      '@id': `${url}#faq`,
      mainEntity: article.faq.map(item => ({
        '@type': 'Question',
        name: H.plain(H.smartQuotes(item.q)),
        acceptedAnswer: {
          '@type': 'Answer',
          text: H.plain(markdown.render(item.a, {}).html.join(' '))
        }
      }))
    });
  }
  return graph;
}

